export function buildRealWorldWordsForLang(langCode: string): WordItem[] | null {
  const extraPack = SOUTH_ASIA_MIDDLE_EAST_EXTRA_WORDS[langCode];
  if (extraPack && extraPack.length > 0) {
    return extraPack.map((item, idx) => {
      const firstChar = Array.from(item.word)[0] || '•';
      return {
        letter: firstChar,
        word: item.word,
        pronunciation: item.pronunciation,
        englishMeaning: item.en,
        translations: {
          en: item.en,
          ur: item.ur,
          [langCode]: item.word,
        },
        icon: item.icon,
        color: BALLOON_COLORS[idx % BALLOON_COLORS.length],
        acceptedMatches: [
          item.word.toLowerCase(),
          item.pronunciation.toLowerCase(),
        ],
      };
    });
  }

  const supported = [
    'en',
    'ur',
    'ar',
    'fa',
    'es',
    'fr',
    'de',
    'tr',
    'it',
    'ru',
    'zh',
    'ja',
    'ko',
    'hi',
  ] as const;
  if (!supported.includes(langCode as any)) return null;

  return MASTER_REAL_WORLD_WORDS.map((seed, idx) => {
    const [word, pronunciation] = seed[langCode as keyof MasterWordSeed] as [
      string,
      string,
    ];
    const [enWord] = seed.en;

    const cleanWord = word.replace(/\s*\([^)]*\)/g, '').trim();
    const firstChar = Array.from(cleanWord)[0] || '•';

    const allTranslations: Record<string, string> = {};
    for (const k of supported) {
      const entry = seed[k];
      if (Array.isArray(entry) && entry[0]) {
        allTranslations[k] = entry[0].replace(/\s*\([^)]*\)/g, '').trim();
      }
    }

    return {
      letter: firstChar,
      word: cleanWord,
      pronunciation,
      englishMeaning: enWord,
      translations: allTranslations,
      icon: seed.icon,
      color: BALLOON_COLORS[idx % BALLOON_COLORS.length],
      acceptedMatches: [
        cleanWord.toLowerCase(),
        pronunciation.toLowerCase(),
        ...cleanWord
          .toLowerCase()
          .split(/\s+/)
          .filter((w) => w.length >= 2),
      ],
    };
  });
}

