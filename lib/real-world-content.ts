export function buildRealWorldConversationsForLang(
  langCode: string
): ConversationItem[] | null {
  const extraConvs = SOUTH_ASIA_MIDDLE_EAST_EXTRA_CONVERSATIONS[langCode];
  if (extraConvs && extraConvs.length > 0) {
    const expanded: ConversationItem[] = [];
    for (let idx = 0; idx < 30; idx++) {
      const item = extraConvs[idx % extraConvs.length];
      const cleanPhrase = item.phrase
        .replace(/[^\p{L}\p{N}\s]/gu, ' ')
        .replace(/\s+/g, ' ')
        .trim()
        .toLowerCase();
      expanded.push({
        situation: `${idx + 1}. ${item.phrase}`,
        phrase: item.phrase,
        pronunciation: item.pronunciation,
        englishMeaning: item.en,
        urduMeaning: item.ur,
        translations: {
          en: item.en,
          ur: item.ur,
          [langCode]: item.phrase,
        },
        replyHint: item.en,
        icon: item.icon,
        color: BALLOON_COLORS[idx % BALLOON_COLORS.length],
        acceptedMatches: [cleanPhrase, item.pronunciation.toLowerCase()],
      });
    }
    return expanded;
  }

  const supported = [
    'en',
    'ur',
    'ar',
    'fa',
    'es',
    'fr',
    'de',
    'tr',
    'it',
    'ru',
    'zh',
    'ja',
    'ko',
    'hi',
  ] as const;
  if (!supported.includes(langCode as any)) {
    return null;
  }
  const targetKey = langCode as (typeof supported)[number];

  return MASTER_REAL_WORLD_CONVERSATIONS.map((seed, idx) => {
    const [phrase, pronunciation] = seed[targetKey as keyof MasterConvSeed] as [
      string,
      string,
    ];
    const [enPhrase] = seed.en;
    const [urPhrase] = seed.ur;

    const allTranslations: Record<string, string> = {};
    for (const k of supported) {
      const entry = seed[k];
      if (Array.isArray(entry) && entry[0]) {
        allTranslations[k] = entry[0];
      }
    }

    const cleanPhrase = phrase
      .replace(/[^\p{L}\p{N}\s]/gu, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .toLowerCase();

    const englishSituation = seed.situation.split('·')[0]?.trim() || `${idx + 1}`;
    const urduSituation = seed.situation.split('·')[1]?.trim() || seed.situation;
    const localizedSituation =
      targetKey === 'ur'
        ? `${idx + 1}. ${urduSituation}`
        : targetKey === 'en'
        ? englishSituation
        : `${idx + 1}. ${allTranslations[targetKey] || phrase}`;

    const localizedReplyHint =
      targetKey === 'ur'
        ? seed.replyHint
        : targetKey === 'en'
        ? enPhrase
        : '';

    return {
      situation: localizedSituation,
      phrase,
      pronunciation,
      englishMeaning: enPhrase,
      urduMeaning: urPhrase,
      translations: allTranslations,
      replyHint: localizedReplyHint,
      icon: seed.icon,
      color: BALLOON_COLORS[idx % BALLOON_COLORS.length],
      acceptedMatches: [cleanPhrase, pronunciation.toLowerCase()],
    };
  });
}

