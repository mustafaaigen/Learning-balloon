function buildPrompts(seed: CompactTranslationSeed): NativeUIPrompts {
  return {
    gameWorld: seed.gameWorld,
    alphabetMode: seed.alphabetMode,
    wordsMode: seed.wordsMode,
    conversationMode: seed.conversationMode,
    changeLanguages: seed.changeLanguages,
    playButton: seed.playButton,
    loadingBalloons: seed.loadingBalloons,
    speakingLabel: seed.speakingLabel,
    learningLabel: seed.learningLabel,
    starsLabel: seed.starsLabel,
    worldSubtitle: seed.worldSubtitle,
    letterLabel: seed.letterLabel,
    wordLabel: seed.wordLabel,
    sentenceLabel: seed.sentenceLabel,
    meaningLabel: seed.meaningLabel,
    gettingReady: (item) => `${seed.gettingReadyPrefix}: ${item}...`,
    listenPrompt: (item) => `🔊 ${seed.listenPrefix}: ${item}`,
    speakingNow: (item) => `${seed.speakingPrefix}: "${item}"`,
    repeatLetterPrompt: seed.repeatPrompt,
    repeatWordPrompt: seed.repeatPrompt,
    repeatPhrasePrompt: seed.repeatPrompt,
    micOnSpeak: (item) => `${seed.micOnPrefix} "${item}"`,
    tapMicSay: (item) => `${seed.tapMicPrefix} "${item}"`,
    tapMicPrompt: (item) => `${seed.tapMicPrefix} "${item}"!`,
    hearAgain: seed.hearAgain,
    checkingPronunciation: seed.checkingPronunciation,
    correctPraise: seed.correctPraise,
    popShabash: seed.popShabash,
    loadingNextBalloon: seed.loadingNextBalloon,
    mistakeWithHeard: seed.mistakeWithHeard,
    mistakeUnclear: seed.mistakeUnclear,
    listenAgainPrompt: (item) => `🔊 ${seed.listenAgainPrefix}: ${item}`,
    prevButton: seed.prevButton,
    nextButton: seed.nextButton,
    heardLabel: (heard) => `${seed.heardPrefix}: "${heard}"`,
    victoryTitle: seed.victoryTitle,
    victorySubtitle: seed.victorySubtitle,
    selectStep1Badge: seed.selectStep1Badge,
    selectStep2Badge: seed.selectStep2Badge,
    selectNativeTitle: seed.selectNativeTitle,
    selectTargetTitle: seed.selectTargetTitle,
    selectNativeSub: seed.selectNativeSub,
    selectTargetSub: seed.selectTargetSub,
    searchNativePlaceholder: seed.searchNativePlaceholder,
    searchTargetPlaceholder: seed.searchTargetPlaceholder,
    backToGame: seed.backToGame,
    dayTheme: seed.dayTheme,
    nightTheme: seed.nightTheme,
  };
}

