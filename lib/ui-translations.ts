  meaningLabel: string;
  gettingReadyPrefix: string;
  listenPrefix: string;
  speakingPrefix: string;
  repeatPrompt: (item: string) => string;
  micOnPrefix: string;
  tapMicPrefix: string;
  hearAgain: string;
  checkingPronunciation: string;
  correctPraise: string;
  popShabash: string;
  loadingNextBalloon: string;
  mistakeWithHeard: (heard: string, target: string) => string;
  mistakeUnclear: (target: string) => string;
  listenAgainPrefix: string;
