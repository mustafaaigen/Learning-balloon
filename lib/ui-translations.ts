// Map closely related language codes to their localized seeds or fallback cleanly
const ALIAS_MAP: Record<string, string> = {
  ms: 'id',
  pa: 'hi',
  ps: 'ur',
  sd: 'ur',
  ku: 'tr',
  uk: 'ru',
};

export function getUIPrompts(langCode: string): NativeUIPrompts {
  const cleanCode = (langCode || 'en').split('-')[0].toLowerCase();
  const seed =
    SEEDS[cleanCode] ||
    (ALIAS_MAP[cleanCode] ? SEEDS[ALIAS_MAP[cleanCode]] : undefined) ||
    SEEDS.en;
  return buildPrompts(seed);
}
