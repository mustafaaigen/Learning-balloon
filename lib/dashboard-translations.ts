export function getDashboardTranslations(lang: LanguageInfo | string): DashboardTranslations {
  const code = typeof lang === 'string' ? lang : lang.code;
  const rtlCodes = ['ur', 'ar', 'fa', 'ps', 'sd', 'he', 'yi', 'ug', 'ku'];
  const base =
    TRANSLATIONS[code] ||
    (rtlCodes.includes(code) ? TRANSLATIONS.fa : TRANSLATIONS.en);

  const renumberTo1 = (s: string) =>
    s.replace(/^2\./, '1.').replace(/^۲\./, '۱.').replace(/^٢\./, '١.').replace(/^২\./, '১.');
  const renumberTo2 = (s: string) =>
    s.replace(/^3\./, '2.').replace(/^۳\./, '۲.').replace(/^٣\./, '٢.').replace(/^৩\./, '২.');

  const navWords = renumberTo1(base.navWords);
  const navConversation = renumberTo2(base.navConversation);

  const stripAlphabetMention = (s: string) =>
    s
      .replace(/Alphabet,\s*/gi, '')
      .replace(/l’Alphabet,\s*/gi, '')
      .replace(/Alfabeto,\s*/gi, '')
      .replace(/Alfabe,\s*/gi, '')
      .replace(/Алфавит,\s*/gi, '')
      .replace(/حروف،\s*/g, '')
      .replace(/الحروف و/g, '')
      .replace(/الفبا،\s*/g, '')
      .replace(/वर्णमाला,\s*/g, '')
      .replace(/বর্ণমালা,\s*/g, '')
      .replace(/文字・/g, '')
      .replace(/문자,\s*/g, '')
      .replace(/字母、/g, '')
      .replace(/3/g, '2')
      .replace(/تینوں/g, 'دونوں')
      .replace(/तीनों/g, 'दोनों')
      .replace(/الثلاث/g, 'المرحلتين');

  return {
    ...base,
    navAlphabet: navWords,
    navWords,
    navConversation,
    skill1Title: navWords,
    skill1Sub: base.skill2Sub,
    skill2Title: navWords,
    skill3Title: navConversation,
    stage1Title: (l: string) =>
      base.stage2Title(l).replace(/2|۲|٢|২/, '1'),
    stage1Sub: (d: number, tCount: number) =>
      base.stage2Sub(d, tCount).replace(/2|۲|٢|২/, '1'),
    stage2Title: (l: string) =>
      base.stage2Title(l).replace(/2|۲|٢|২/, '1'),
    stage2Sub: (d: number, tCount: number) =>
      base.stage2Sub(d, tCount).replace(/2|۲|٢|২/, '1'),
    stage3Title: (l: string) =>
      base.stage3Title(l).replace(/3|۳|٣|৩/, '2'),
    stage3Sub: (d: number, tCount: number) =>
      base.stage3Sub(d, tCount).replace(/3|۳|٣|৩/, '2'),
    heroSubtitle: (flag, l, wD, wT, cD, cT) =>
      `${flag} ${l} — ${base.skill2Sub(wD, wT)} • ${base.skill3Sub(cD, cT)}`,
    certCardLockedDesc: stripAlphabetMention(base.certCardLockedDesc),
    certRewardLockedDesc: (l: string) =>
      stripAlphabetMention(base.certRewardLockedDesc(l)),
    stagesCompletedLabel: (c) =>
      base.stagesCompletedLabel(c).replace(/\/3|\/۳|\/٣|\/৩/, '/2'),
  };
}


