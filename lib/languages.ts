export interface LanguageInfo {
  code: string;
  name: string;
  nativeName: string;
  flag: string;
  bcp47: string;
  rtl?: boolean;
  region: string;
}

export interface AlphabetItem {
  letter: string;
  name: string; // How the letter is pronounced / named (e.g., "Ay", "Alif", "Be")
  phonetic: string; // Phonetic hint for the learner
  ttsPrompt: string; // What the TTS should speak clearly
  acceptedMatches: string[]; // Acceptable lowercase transcriptions / phonetic equivalents
}

export interface WordItem {
  letter: string;
  word: string;
  pronunciation: string;
  englishMeaning: string;
  translations: Record<string, string>; // Native language code -> meaning
  icon: string; // Large clear emoji / visual symbol
  color: string; // Balloon theme color
  acceptedMatches: string[];
}

export interface ConversationItem {
  situation: string;
  phrase: string;
  pronunciation: string;
  englishMeaning: string;
  urduMeaning: string;
  translations: Record<string, string>;
  replyHint?: string;
  icon: string;
  color: string;
  acceptedMatches: string[];
}

export interface LanguageCurriculum {
  alphabet: AlphabetItem[];
  words: WordItem[];
  conversations?: ConversationItem[];
}

